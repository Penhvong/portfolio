(function(){
  if(typeof document==='undefined')return;
  var lang='en';
  try{lang=localStorage.getItem('lang')||(/^km/i.test(navigator.language)?'km':'en');}catch(e){}

  var nodes=[],w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT),n;
  while((n=w.nextNode())){
    var p=n.parentNode.nodeName;
    if(p==='SCRIPT'||p==='STYLE'||!n.nodeValue.trim())continue;
    nodes.push({node:n,orig:n.nodeValue});
  }
  var attrEls=[].slice.call(document.querySelectorAll('[aria-label],[alt],[placeholder]'));
  var meta=document.querySelector('meta[name="description"]');
  var origTitle=document.title,origMeta=meta?meta.content:'';
  function key(s){return s.trim().replace(/\s+/g,' ');}
  function tr(s,l){return l==='km'&&I18N.km[s]?I18N.km[s]:s;}

  function apply(l){
    lang=l;
    document.documentElement.lang=l==='km'?'km':'en';
    nodes.forEach(function(o){
      var k=key(o.orig),lead=o.orig.match(/^\s*/)[0],trail=o.orig.match(/\s*$/)[0];
      o.node.nodeValue=l==='km'&&I18N.km[k]?lead+I18N.km[k]+trail:o.orig;
    });
    attrEls.forEach(function(el){
      ['aria-label','alt','placeholder'].forEach(function(a){
        if(!el.hasAttribute(a))return;
        if(!el.hasAttribute('data-en-'+a))el.setAttribute('data-en-'+a,el.getAttribute(a));
        el.setAttribute(a,tr(el.getAttribute('data-en-'+a),l));
      });
    });
    document.title=tr(origTitle,l);
    if(meta)meta.content=tr(origMeta,l);
    var b=document.getElementById('lang');
    if(b){b.textContent=l==='km'?'EN':'ខ្មែរ';b.setAttribute('aria-label',l==='km'?'Switch to English':'ប្តូរទៅភាសាខ្មែរ');}
    try{localStorage.setItem('lang',l);}catch(e){}
    document.dispatchEvent(new Event('langchange'));
  }

  window.t=function(s){return tr(s,lang);};
  window.getLang=function(){return lang;};
  window.getTypedWords=function(){return I18N.typed[lang];};

  var btn=document.getElementById('lang');
  if(btn)btn.addEventListener('click',function(){apply(lang==='km'?'en':'km');});
  apply(lang);
})();
